// Draws `text` with the 5x7 font onto a new canvas at `scale`, in `color`. Unknown characters become a gap.
function bitmapText(text, scale, color) {
  const glyphs = [...text].map((ch) => FONT57[ch] || FONT57[ch.toUpperCase()] || FONT57[' ']);
  const width = glyphs.reduce((w, g) => w + g[0].length + 1, 0) - 1;
  const cv = document.createElement('canvas');
  cv.width = Math.max(1, width) * scale; cv.height = 10 * scale;
  const g = cv.getContext('2d'); g.fillStyle = color;
  let x = 0;
  for (const gl of glyphs) {
    gl.forEach((row, y) => [...row].forEach((c, i) => { if (c === '1') g.fillRect((x + i) * scale, (y + 1) * scale, scale, scale); }));
    x += gl[0].length + 1;
  }
  cv.style.width = cv.width + 'px'; cv.style.height = cv.height + 'px';
  return cv;
}
// Like bitmapText, but wraps words onto new lines so no line is wider than `maxWidth` (css px).
function bitmapLines(text, scale, color, maxWidth) {
  const adv = (s) => [...s].reduce((w, ch) => w + ((FONT57[ch] || FONT57[ch.toUpperCase()] || FONT57[' '])[0].length + 1), 0) * scale;
  const lines = [];
  let line = '';
  for (const word of text.split(' ')) {
    const next = line ? line + ' ' + word : word;
    if (line && maxWidth && adv(next) > maxWidth) { lines.push(line); line = word; } else line = next;
  }
  if (line) lines.push(line);
  const parts = lines.map((l) => bitmapText(l, scale, color));
  const cv = document.createElement('canvas');
  cv.width = Math.max(...parts.map((p) => p.width)); cv.height = parts.length * 10 * scale;
  const g = cv.getContext('2d');
  parts.forEach((p, i) => g.drawImage(p, 0, i * 10 * scale));
  cv.style.width = cv.width + 'px'; cv.style.height = cv.height + 'px';
  return cv;
}
